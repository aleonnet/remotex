def swap(old, new):
    def planted(text):
        assert text.count(old) == 1, f"the place to plant it is there {text.count(old)} times: {old[:70]}"
        return text.replace(old, new)

    return planted


def unit(test):
    """The page's unit tests of one file."""
    return (["bun", "test", f"src/{test}"], ROOT / "frontend", {})


def browser(spec, title):
    """One browser test against the harness, which is built again with the defect in it.
    In Chromium alone: a defect is planted in the page, and one engine reading it is the proof."""
    return (["bash", "tools/run-page-tests.sh", "-g", title], ROOT,
            {"ALUMIA_PAGE_SPECS": spec, "ALUMIA_PAGE_WEBKIT_SPECS": ""})


def server(test):
    """The gateway's unit tests whose name holds `test`."""
    return (["cargo", "test", "--lib", test], ROOT, {})


def wire(test):
    """The protocol's end-to-end tests whose name holds `test`, against the scripted Mac."""
    return (["cargo", "test", "--test", "protocol_e2e", test], ROOT, {})


def hosted(test):
    """The end-to-end tests of the gateway a Mac app hosts whose name holds `test`: the real binary."""
    return (["cargo", "test", "--test", "app_mode_e2e", test], ROOT, {})


def app(tests):
    """The Mac app's tests of one class."""
    return (["swift", "test", "--filter", tests], ROOT / "macos/Alumia", {})


