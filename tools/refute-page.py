#!/usr/bin/env python3
"""Prove that the product's tests fail when they should.

Each proof plants one defect in the product's code (the page, the gateway, the Mac app, or
what their words are checked against), runs the check that is meant to catch it, and
requires the check to fail saying the exact words given here. The file is put back as it
was, whatever happens, and its digest is compared with the one taken before. A test that
goes on passing over a planted defect protects nothing, and this is how that is found out.

It is not a gate: it takes minutes, because a proof that needs a browser compiles the page
into the gateway's test harness first, and one of the gateway or the Mac app compiles that.
Run it before a commit that changes the rules it plants in, or the tests that catch them,
and never beside another build: the defect is in the tree while its check runs.

    uv run --no-project python tools/refute-page.py              every proof
    uv run --no-project python tools/refute-page.py --anchors    only that each defect still
                                                                 finds its place, with no check run
    uv run --no-project python tools/refute-page.py view-only-menu caps    those proofs alone
"""

