def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()[:12]


def prove(proof):
    name, what, file, plant, (command, where, extra), words = proof
    path = ROOT / file
    before, original = digest(path), path.read_text(encoding="utf-8")
    started = time.time()
    try:
        path.write_text(plant(original), encoding="utf-8")
        ran = subprocess.run(command, cwd=where, env={**os.environ, **extra}, capture_output=True, text=True)
    finally:
        path.write_text(original, encoding="utf-8")
    said = ran.stdout + ran.stderr
    restored = digest(path) == before
    missing = [word for word in words if word not in said]
    proved = ran.returncode != 0 and not missing and restored
    print(f"{'PROVED    ' if proved else 'NOT PROVED'} {name}  {what}")
    print(f"    exit {ran.returncode}; restored {restored} ({before}); {time.time() - started:.0f} s")
    for line in said.splitlines():
        if any(word in line for word in words):
            print(f"    {line.strip()[:200]}")
            break
    for word in missing:
        print(f"    did not say: {word}")
    if not proved:
        print("    " + "\n    ".join(said.strip().splitlines()[-40:]))
    return proved


def main():
    if sys.argv[1:] == ["--anchors"]:
        lost = 0
        for name, what, file, plant, _, _ in PROOFS:
            try:
                plant((ROOT / file).read_text(encoding="utf-8"))
            except AssertionError as gone:
                lost += 1
                print(f"LOST {name}  {what}: {gone}")
        print(f"{len(PROOFS) - lost} of {len(PROOFS)} defects find their place")
        return 1 if lost else 0
    wanted = sys.argv[1:]
    proofs = [proof for proof in PROOFS if not wanted or proof[0] in wanted]
    proved = sum(prove(proof) for proof in proofs)
    print(f"\n{proved} of {len(proofs)} proved")
    return 0 if proved == len(proofs) else 1


if __name__ == "__main__":
    sys.exit(main())
